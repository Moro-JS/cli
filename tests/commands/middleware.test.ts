// middleware list / add – what is listed against what can be generated.
import { promises as fs } from 'fs';
import { join } from 'path';
import { tmpdir } from 'os';
import { ADDABLE_MIDDLEWARE, MiddlewareManager } from '../../src/commands/middleware';

describe('MiddlewareManager', () => {
  let workDir: string;
  let originalCwd: string;
  let manager: MiddlewareManager;
  let lines: string[];

  beforeEach(async () => {
    originalCwd = process.cwd();
    workDir = await fs.mkdtemp(join(tmpdir(), 'moro-mw-'));
    await fs.mkdir(join(workDir, 'src', 'middleware'), { recursive: true });
    process.chdir(workDir);

    manager = new MiddlewareManager();
    lines = [];
    const record = (message: string) => lines.push(message);
    (manager as any).logger = { info: record, warn: record, error: record, debug: record };
  });

  afterEach(async () => {
    process.chdir(originalCwd);
    await fs.rm(workDir, { recursive: true, force: true });
  });

  test('list shows the type names that add takes, apart from the ones it cannot generate', async () => {
    await manager.listMiddleware();

    const generatedAt = lines.findIndex(line =>
      line.includes('Generated by "middleware add <type>"')
    );
    const othersAt = lines.findIndex(line => line.includes('Other built-in middleware'));
    expect(generatedAt).toBeGreaterThan(-1);
    expect(othersAt).toBeGreaterThan(generatedAt);

    const names = (from: number, to: number) =>
      lines
        .slice(from + 1, to)
        .map(line => line.trim().split(/\s+/)[0])
        .filter(Boolean);

    const usageAt = lines.findIndex(line => line.startsWith('Usage:'));
    expect(names(generatedAt, othersAt)).toEqual(ADDABLE_MIDDLEWARE);
    expect(names(othersAt, usageAt)).toEqual([
      'cookie',
      'session',
      'csrf',
      'csp',
      'sse',
      'cdn',
      'request-logger',
      'performance-monitor',
      'error-tracker',
    ]);
  });

  test('every type listed as generated is accepted by add', async () => {
    for (const type of ADDABLE_MIDDLEWARE) {
      await expect(manager.addMiddleware(type, {})).resolves.toBeUndefined();
    }
    const written = await fs.readdir(join(workDir, 'src', 'middleware'));
    expect(written).toHaveLength(ADDABLE_MIDDLEWARE.length);

    // A type from the other group has no generator.
    await expect(manager.addMiddleware('csrf', {})).rejects.toThrow(
      'Unsupported middleware type: csrf'
    );
  });

  describe('generated setup files', () => {
    const read = (file: string) => fs.readFile(join(workDir, 'src', 'middleware', file), 'utf8');

    // Names a setup file imports from the framework.
    const frameworkImports = (source: string): string[] =>
      (/import \{([^}]+)\} from '@morojs\/moro';/.exec(source)?.[1] ?? '')
        .split(',')
        .map(name => name.trim())
        .filter(Boolean);

    // The generated file is valid TypeScript on its own (no missing commas or
    // undeclared identifiers left over from a template).
    function expectValidSyntax(source: string): void {
      // eslint-disable-next-line @typescript-eslint/no-var-requires
      const ts = require('typescript') as typeof import('typescript');
      const result = ts.transpileModule(source, {
        reportDiagnostics: true,
        compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
      });
      expect(result.diagnostics).toEqual([]);
    }

    test.each([
      ['cors', 'cors_middleware.ts', 'middleware.cors({'],
      ['rate-limit', 'rate_limit_middleware.ts', 'middleware.rateLimit({'],
      ['cache', 'cache_middleware.ts', 'middleware.cache({'],
      ['validation', 'validation_middleware.ts', 'middleware.validation()'],
      ['helmet', 'helmet_middleware.ts', 'middleware.helmet({'],
      ['compression', 'compression_middleware.ts', 'middleware.compression({'],
    ])('%s is built from the middleware export of the framework', async (type, file, call) => {
      await manager.addMiddleware(type, {});

      const source = await read(file);
      // The factories are members of `middleware`; they are not root exports.
      expect(frameworkImports(source)).toEqual(['middleware']);
      expect(source).toContain(call);
      expectValidSyntax(source);
    });

    // The file without its comments: what is compiled.
    const code = (source: string) =>
      source
        .split('\n')
        .filter(line => !line.trim().startsWith('//'))
        .join('\n');

    test('auth passes a secret, a session, OAuth providers and email and password to auth()', async () => {
      await manager.addMiddleware('auth', {});

      const source = await read('auth_middleware.ts');
      expect(frameworkImports(source)).toEqual(['auth', 'providers']);
      expect(source).toContain('export const authMiddleware = auth({');
      expect(source).toContain('secret: process.env.JWT_SECRET');
      expect(source).toMatch(/session: \{\s+maxAge: 86400/);
      expect(source).toContain('providers: oauthProviders()');
      // Email and password is an option of Better Auth, handed through.
      expect(source).toMatch(/betterAuth: \{[\s\S]*emailAndPassword: \{ enabled: true \}/);
      // Not options of auth(): they made the file fail to compile.
      expect(source).not.toMatch(/^\s*(expiresIn|algorithms):/m);
      expectValidSyntax(source);
    });

    test('auth writes none of the keys Better Auth has no equivalent for', async () => {
      await manager.addMiddleware('auth', {
        config:
          '{"strategy":"jwt","trustHost":true,"basePath":"/auth","baseURL":"https://app.example.com"}',
      });

      const source = code(await read('auth_middleware.ts'));
      // Each of these is named in a start-up warning by the framework's adapter.
      expect(source).not.toContain('providers.credentials');
      expect(source).not.toMatch(/\b(strategy|trustHost|callbacks)\s*:/);
      // The options it does take are written as given.
      expect(source).toContain('basePath: "/auth"');
      expect(source).toContain('baseURL: "https://app.example.com"');
      expectValidSyntax(source);

      const output = lines.join('\n');
      expect(output).toContain(
        'not applied to the auth middleware (it has no matching option): strategy, trustHost'
      );
      expect(output).toContain('strategy has no equivalent: sessions are stored in the database');
      expect(output).toContain('trustHost has no equivalent: set baseURL');
    });

    test('auth assumes no database of the project and says what it starts on', async () => {
      await manager.addMiddleware('auth', {});

      const source = await read('auth_middleware.ts');
      const comments = source
        .split('\n')
        .filter(line => line.startsWith('//'))
        .map(line => line.replace(/^\/\/ ?/, ''))
        .join(' ');
      expect(comments).toContain('email and password sign-in needs one');
      expect(comments).toContain(
        'everything is gone at restart, and nothing is shared between processes'
      );
      expect(comments).toContain('https://better-auth.com/docs/concepts/database');

      const compiled = code(source);
      expect(compiled).toContain(`import { memoryAdapter } from 'better-auth/adapters/memory';`);
      expect(compiled).toMatch(/database: memoryAdapter\(\{ user: \[\], session: \[\]/);
      expect(compiled).not.toMatch(/app\.database|better-sqlite3|from 'pg'|mysql2/);
    });

    test('auth says when the package its file imports is not in package.json', async () => {
      await fs.writeFile(join(workDir, 'package.json'), JSON.stringify({ dependencies: {} }));
      await manager.addMiddleware('auth', {});
      expect(lines.join('\n')).toContain('Add it with: npm install better-auth');

      lines.length = 0;
      await fs.writeFile(
        join(workDir, 'package.json'),
        JSON.stringify({ dependencies: { 'better-auth': '^1.7.7' } })
      );
      await manager.addMiddleware('auth', {});
      expect(lines.join('\n')).not.toContain('npm install better-auth');
    });

    test('auth maps expiresIn, and reports the keys it cannot apply', async () => {
      await manager.addMiddleware('auth', {
        config: '{"expiresIn":"7d","algorithms":["HS512"],"roles":["admin"]}',
      });

      const source = await read('auth_middleware.ts');
      expect(source).toMatch(/session: \{\s+maxAge: 604800/);
      expect(lines.join('\n')).toContain(
        'not applied to the auth middleware (it has no matching option): algorithms, roles'
      );
    });

    test('rate-limit keeps windowMs / max and accepts the window / requests spelling', async () => {
      await manager.addMiddleware('rate-limit', { config: '{"windowMs":1000,"max":5}' });
      let source = await read('rate_limit_middleware.ts');
      expect(source).toContain('windowMs: 1000');
      expect(source).toContain('max: 5');
      // Options of another library; they are not options of this factory.
      expect(source).not.toMatch(/standardHeaders|legacyHeaders/);
      expect(lines.join('\n')).not.toContain('not applied');

      await manager.addMiddleware('rate-limit', {
        config: '{"requests":5,"window":1000,"legacyHeaders":false}',
      });
      source = await read('rate_limit_middleware.ts');
      expect(source).toContain('requests: 5');
      expect(source).toContain('window: 1000');
      expect(source).not.toMatch(/windowMs|max:/);
      expect(lines.join('\n')).toContain('no matching option): legacyHeaders');
    });

    test('cache maps ttl to defaultTtl and a store name in strategy to adapter', async () => {
      await manager.addMiddleware('cache', { config: '{"ttl":60,"strategy":"redis"}' });
      let source = await read('cache_middleware.ts');
      expect(source).toContain('defaultTtl: 60');
      expect(source).toContain('adapter: "redis"');
      expect(source).not.toMatch(/^\s*(ttl|strategy|max):/m);
      expect(lines.join('\n')).not.toContain('not applied');

      // The old defaults (an eviction policy and an entry limit) have no option.
      await manager.addMiddleware('cache', { config: '{"max":10,"strategy":"lru"}' });
      source = await read('cache_middleware.ts');
      expect(source).toContain('adapter: "memory"');
      expect(source).toContain('defaultTtl: 300');
      expect(lines.join('\n')).toContain('no matching option): max, strategy');
    });

    test('helmet maps the helmet package names to the option names of the factory', async () => {
      await manager.addMiddleware('helmet', {
        config: '{"frameguard":false,"hsts":false,"noSniff":true,"hidePoweredBy":true}',
      });

      const source = await read('helmet_middleware.ts');
      expect(source).toContain('xFrameOptions: false');
      expect(source).toContain('strictTransportSecurity: false');
      expect(source).toContain('xContentTypeOptions: true');
      expect(source).not.toMatch(/frameguard|hsts|noSniff|crossOrigin|hidePoweredBy/);
      expect(lines.join('\n')).toContain('no matching option): hidePoweredBy');
    });

    test('compression takes level and threshold and has no undeclared filter identifier', async () => {
      await manager.addMiddleware('compression', {
        config: '{"level":9,"filter":"shouldCompress"}',
      });

      const source = await read('compression_middleware.ts');
      expect(source).toContain('level: 9');
      expect(source).toContain('threshold: 1024');
      expect(source).not.toMatch(/^\s*filter: shouldCompress/m);
      expect(lines.join('\n')).toContain('no matching option): filter');
    });

    test('validation takes no options and says where its old keys belong', async () => {
      await manager.addMiddleware('validation', { config: '{"stripUnknown":false}' });

      expect(await read('validation_middleware.ts')).toContain(
        'export const validationMiddleware = middleware.validation();'
      );
      expect(lines.join('\n')).toContain('no matching option): stripUnknown');
      expect(lines.join('\n')).toContain('modules.validation in moro.config.ts');
    });
  });
});
