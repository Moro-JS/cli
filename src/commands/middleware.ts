// Middleware Management - Add and configure built-in middleware
import { writeFile } from 'fs/promises';
import { existsSync, readFileSync } from 'fs';
import { join } from 'path';
import { createFrameworkLogger } from '../logger';
import { authMiddlewareSource } from '../utils/auth-templates';

/** A generated setup file plus the --config keys that could not be applied to it. */
interface RenderedMiddleware {
  code: string;
  /** Keys the user passed that have no matching option; reported in one warning. */
  unapplied: string[];
  /** Extra hints printed after the file is written. */
  notes?: string[];
}

type Config = Record<string, unknown>;

// TypeScript literal for a value that came from --config JSON.
const literal = (value: unknown): string => JSON.stringify(value);

/**
 * Renders `key: value` lines for the given option names, in order, skipping
 * the ones the configuration does not set.
 */
function optionLines(config: Config, names: readonly string[], indent = '  '): string {
  return names
    .filter(name => config[name] !== undefined)
    .map(name => `${indent}${name}: ${literal(config[name])}`)
    .join(',\n');
}

/** "24h", "7d", "30m", "45s" or a number of seconds, as seconds. */
function durationToSeconds(value: unknown): number | undefined {
  if (typeof value === 'number' && Number.isFinite(value) && value > 0) return Math.floor(value);
  if (typeof value !== 'string') return undefined;
  const match = /^(\d+)\s*(s|m|h|d|w)?$/i.exec(value.trim());
  if (!match) return undefined;
  const unit = { s: 1, m: 60, h: 3600, d: 86400, w: 604800 }[(match[2] || 's').toLowerCase()];
  return unit ? parseInt(match[1], 10) * unit : undefined;
}

export interface MiddlewareOptions {
  config?: string;
}

// Types "middleware add" has a setup template for.
export const ADDABLE_MIDDLEWARE = [
  'auth',
  'cors',
  'rate-limit',
  'cache',
  'validation',
  'helmet',
  'compression',
];

export class MiddlewareManager {
  private logger = createFrameworkLogger('MiddlewareManager');

  async addMiddleware(type: string, options: MiddlewareOptions): Promise<void> {
    this.logger.info(`Adding ${type} middleware...`, 'Middleware');

    try {
      const userConfig = this.parseUserConfig(options.config);
      const rendered = this.renderMiddleware(type, userConfig);
      await this.writeMiddlewareSetup(type, rendered.code);

      if (rendered.unapplied.length > 0) {
        this.logger.warn(
          `--config: not applied to the ${type} middleware (it has no matching option): ` +
            rendered.unapplied.join(', '),
          'Middleware'
        );
      }
      for (const note of rendered.notes || []) this.logger.warn(note, 'Middleware');

      this.logger.info(`✅ ${type} middleware added successfully!`, 'Middleware');
      this.logger.info('Import and use in your main app file', 'Middleware');
    } catch (error) {
      this.logger.error(
        `Failed to add middleware: ${error instanceof Error ? error.message : 'Unknown error'}`,
        'Middleware'
      );
      throw error;
    }
  }

  async listMiddleware(): Promise<void> {
    // `generator: true` marks the types "middleware add <type>" can write a
    // setup file for. The rest ship with the framework but have no generator.
    const middleware = [
      { name: 'auth', description: 'Authentication & Authorization (JWT, Session, OAuth)' },
      { name: 'cors', description: 'Cross-Origin Resource Sharing' },
      { name: 'rate-limit', description: 'Rate limiting and throttling' },
      { name: 'cache', description: 'Response caching (Memory, Redis, File)' },
      { name: 'validation', description: 'Request validation (Zod-based)' },
      { name: 'helmet', description: 'Security headers' },
      { name: 'compression', description: 'Response compression (gzip, brotli)' },
      { name: 'cookie', description: 'Cookie parsing and management' },
      { name: 'session', description: 'Session management' },
      { name: 'csrf', description: 'CSRF protection' },
      { name: 'csp', description: 'Content Security Policy' },
      { name: 'sse', description: 'Server-Sent Events' },
      { name: 'cdn', description: 'CDN integration (Cloudflare, AWS, Azure)' },
      { name: 'request-logger', description: 'HTTP request logging' },
      { name: 'performance-monitor', description: 'Performance monitoring' },
      { name: 'error-tracker', description: 'Error tracking and reporting' },
    ].map(mw => ({ ...mw, generator: ADDABLE_MIDDLEWARE.includes(mw.name) }));

    const width = Math.max(...middleware.map(mw => mw.name.length));
    const line = (mw: { name: string; description: string }) =>
      `   ${mw.name.padEnd(width)}  ${mw.description}`;

    this.logger.info('Generated by "middleware add <type>":', 'Middleware');
    middleware.filter(mw => mw.generator).forEach(mw => this.logger.info(line(mw), 'Middleware'));
    this.logger.info('', 'Middleware');
    this.logger.info(
      'Other built-in middleware (no generator; use the middleware export of @morojs/moro):',
      'Middleware'
    );
    middleware.filter(mw => !mw.generator).forEach(mw => this.logger.info(line(mw), 'Middleware'));
    this.logger.info('', 'Middleware');
    this.logger.info(
      'Usage: morojs-cli middleware add <type> [--config=\'{"key":"value"}\']',
      'Middleware'
    );
  }

  /** The --config JSON as an object; anything else falls back to the defaults. */
  private parseUserConfig(configStr?: string): Config {
    if (!configStr) return {};
    try {
      const parsed = JSON.parse(configStr);
      if (parsed && typeof parsed === 'object' && !Array.isArray(parsed)) return parsed as Config;
    } catch {
      // handled below
    }
    this.logger.warn('Invalid JSON config, using defaults', 'Middleware');
    return {};
  }

  /**
   * Renders the setup file for one middleware type. Every template calls the
   * factory the framework exports with the option names that factory takes.
   * A --config key keeps being accepted: it is mapped to the real option when
   * there is one, and listed in `unapplied` when there is none.
   */
  private renderMiddleware(type: string, user: Config): RenderedMiddleware {
    const renderers: Record<string, (user: Config) => RenderedMiddleware> = {
      auth: cfg => this.renderAuth(cfg),
      cors: cfg => this.renderCors(cfg),
      'rate-limit': cfg => this.renderRateLimit(cfg),
      cache: cfg => this.renderCache(cfg),
      validation: cfg => this.renderValidation(cfg),
      helmet: cfg => this.renderHelmet(cfg),
      compression: cfg => this.renderCompression(cfg),
    };

    const render = renderers[type];
    if (!render) {
      throw new Error(`Unsupported middleware type: ${type}`);
    }
    return render(user);
  }

  private renderCors(user: Config): RenderedMiddleware {
    const names = [
      'origin',
      'methods',
      'allowedHeaders',
      'exposedHeaders',
      'credentials',
      'maxAge',
      'preflightContinue',
    ];
    const config: Config = {
      origin: '*',
      methods: ['GET', 'POST', 'PUT', 'DELETE', 'PATCH', 'OPTIONS'],
      allowedHeaders: ['Content-Type', 'Authorization'],
      credentials: false,
      ...user,
    };

    return {
      code: `// CORS Middleware Setup
import { middleware } from '@morojs/moro';

export const corsMiddleware = middleware.cors({
${optionLines(config, names)}
});

// Usage in your app:
// app.use(corsMiddleware);`,
      unapplied: Object.keys(user).filter(key => !names.includes(key)),
    };
  }

  private renderRateLimit(user: Config): RenderedMiddleware {
    // windowMs / max and window / requests are two spellings of the same options.
    const names = [
      'windowMs',
      'window',
      'max',
      'requests',
      'message',
      'statusCode',
      'skipSuccessfulRequests',
      'skipFailedRequests',
    ];
    const config: Config = {
      ...(user.window === undefined && { windowMs: 60000 }),
      ...(user.requests === undefined && { max: 100 }),
      message: 'Too many requests from this IP',
      ...user,
    };

    return {
      code: `// Rate Limiting Middleware Setup
import { middleware } from '@morojs/moro';

// Requests over the limit are answered with 429 and a Retry-After header.
export const rateLimitMiddleware = middleware.rateLimit({
${optionLines(config, names)}
});

// Usage in your app:
// app.use(rateLimitMiddleware);`,
      unapplied: Object.keys(user).filter(key => !names.includes(key)),
    };
  }

  private renderCache(user: Config): RenderedMiddleware {
    const passthrough = [
      'adapterOptions',
      'strategies',
      'keyPrefix',
      'httpCaching',
      'maxAge',
      'cacheControl',
      'staleWhileRevalidate',
      'vary',
      'etag',
      'conditionalRequests',
    ];
    const adapters = ['memory', 'redis', 'file'];
    const applied = ['ttl', 'defaultTtl', 'adapter', ...passthrough];

    // `ttl` is the lifetime in seconds: the factory calls it defaultTtl.
    // `strategy` selects the store when it names one (memory, redis, file).
    const strategyIsAdapter = typeof user.strategy === 'string' && adapters.includes(user.strategy);
    if (strategyIsAdapter) applied.push('strategy');

    const config: Config = {
      adapter: user.adapter ?? (strategyIsAdapter ? user.strategy : 'memory'),
      defaultTtl: user.defaultTtl ?? user.ttl ?? 300,
    };
    for (const name of passthrough) {
      if (user[name] !== undefined) config[name] = user[name];
    }

    return {
      code: `// Cache Middleware Setup
import { middleware } from '@morojs/moro';

// Keeps one response per URL and replays it (X-Cache: HIT) until it expires.
export const cacheMiddleware = middleware.cache({
${optionLines(config, ['adapter', 'defaultTtl', ...passthrough])}
});

// Usage in your app:
// app.use(cacheMiddleware);`,
      unapplied: Object.keys(user).filter(key => !applied.includes(key)),
    };
  }

  private renderValidation(user: Config): RenderedMiddleware {
    const keys = Object.keys(user);
    return {
      code: `// Validation Middleware Setup
import { middleware } from '@morojs/moro';

// middleware.validation() takes no options. Request bodies, queries and params
// are validated per route with .body() / .query() / .params(), and the
// stripUnknown / abortEarly behaviour is set under modules.validation in
// moro.config.ts.
export const validationMiddleware = middleware.validation();

// Usage in your app:
// app.use(validationMiddleware);`,
      unapplied: keys,
      notes: keys.some(key => ['stripUnknown', 'abortEarly', 'allowUnknown'].includes(key))
        ? [
            'stripUnknown / abortEarly / allowUnknown are settings of modules.validation in ' +
              'moro.config.ts, not of this middleware.',
          ]
        : [],
    };
  }

  private renderHelmet(user: Config): RenderedMiddleware {
    // The helmet package's option names, mapped to the names this factory takes.
    const aliases: Record<string, string> = {
      frameguard: 'xFrameOptions',
      hsts: 'strictTransportSecurity',
      noSniff: 'xContentTypeOptions',
      xssFilter: 'xXssProtection',
      ieNoOpen: 'xDownloadOptions',
      permittedCrossDomainPolicies: 'xPermittedCrossDomainPolicies',
    };
    const names = [
      'contentSecurityPolicy',
      'xFrameOptions',
      'xContentTypeOptions',
      'xXssProtection',
      'referrerPolicy',
      'strictTransportSecurity',
      'xDownloadOptions',
      'xPermittedCrossDomainPolicies',
    ];

    const config: Config = {
      contentSecurityPolicy: true,
      xFrameOptions: true,
      xContentTypeOptions: true,
      xXssProtection: true,
      referrerPolicy: true,
      strictTransportSecurity: true,
      xDownloadOptions: true,
      xPermittedCrossDomainPolicies: false,
    };
    const unapplied: string[] = [];
    for (const [key, value] of Object.entries(user)) {
      const name = aliases[key] || key;
      if (names.includes(name)) config[name] = value;
      else unapplied.push(key);
    }

    return {
      code: `// Security Headers Middleware Setup
import { middleware } from '@morojs/moro';

export const helmetMiddleware = middleware.helmet({
${optionLines(config, names)}
});

// Usage in your app:
// app.use(helmetMiddleware);`,
      unapplied,
    };
  }

  private renderCompression(user: Config): RenderedMiddleware {
    // `filter` is a function in the framework, which JSON cannot carry.
    const names = ['level', 'threshold', 'encodings', 'maxInlineBytes'];
    const config: Config = { level: 6, threshold: 1024, ...user };

    return {
      code: `// Compression Middleware Setup
import { middleware } from '@morojs/moro';

export const compressionMiddleware = middleware.compression({
${optionLines(config, names)}
  // filter: (req, res) => true  // decide per response whether to compress
});

// Usage in your app:
// app.use(compressionMiddleware);`,
      unapplied: Object.keys(user).filter(key => !names.includes(key)),
    };
  }

  private renderAuth(user: Config): RenderedMiddleware {
    // Options of auth() that JSON can carry and that are written as they are.
    const passthrough = ['basePath', 'baseURL', 'trustedOrigins', 'debug', 'useSecureCookies'];
    const applied = ['secret', ...passthrough];
    const notes: string[] = [];

    // `expiresIn` is the session lifetime, which the factory takes in seconds.
    let maxAge = 24 * 60 * 60;
    if (user.expiresIn !== undefined) {
      const seconds = durationToSeconds(user.expiresIn);
      if (seconds !== undefined) {
        maxAge = seconds;
        applied.push('expiresIn');
      }
    }

    // The secret is read from the environment unless a literal value is given.
    const secret =
      typeof user.secret === 'string' && !user.secret.startsWith('process.env.')
        ? literal(user.secret)
        : typeof user.secret === 'string'
          ? user.secret
          : 'process.env.JWT_SECRET';

    // Keys of an Auth.js configuration that sign-in on Better Auth has no
    // option for: the framework would name each in a start-up warning.
    if (user.strategy !== undefined) {
      notes.push(
        'strategy has no equivalent: sessions are stored in the database given as ' +
          'betterAuth.database in the generated file.'
      );
    }
    if (user.trustHost !== undefined) {
      notes.push('trustHost has no equivalent: set baseURL to the URL the app is reached at.');
    }

    if (!this.projectHasDependency('better-auth')) {
      notes.push(
        'The auth middleware imports the "better-auth" package, which is not in this ' +
          "project's package.json. Add it with: npm install better-auth"
      );
    }

    return {
      code: authMiddlewareSource({
        secret,
        maxAge,
        extraOptions: optionLines(user, passthrough),
      }),
      unapplied: Object.keys(user).filter(key => !applied.includes(key)),
      notes,
    };
  }

  /** True when package.json in the current directory lists the dependency (or cannot be read). */
  private projectHasDependency(dependency: string): boolean {
    const file = join(process.cwd(), 'package.json');
    if (!existsSync(file)) return true;
    try {
      const pkg = JSON.parse(readFileSync(file, 'utf8'));
      return Boolean(
        pkg.dependencies?.[dependency] ||
        pkg.devDependencies?.[dependency] ||
        pkg.peerDependencies?.[dependency]
      );
    } catch {
      return true;
    }
  }

  private async writeMiddlewareSetup(type: string, middlewareCode: string): Promise<void> {
    const fileName = `${type.replace('-', '_')}_middleware.ts`;

    await writeFile(join(process.cwd(), 'src', 'middleware', fileName), middlewareCode);

    this.logger.info(`Created: src/middleware/${fileName}`, 'Middleware');
  }
}
